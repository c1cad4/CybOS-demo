#!/usr/bin/env python3
"""Prepare an additional peer without modifying the original server or live tunnel."""
import argparse
import configparser
from pathlib import Path
import json

from prepare_wireguard_server import public_key, validate, wg_run, write_new


def enroll(source, output, endpoint, address, device_key, tool='wg'):
    device_key, address = validate(endpoint, address, device_key)
    source = Path(source)
    output = Path(output)
    if output.exists() or output.is_symlink():
        raise ValueError('Output directory already exists; existing files are never replaced')
    if source.is_symlink() or not source.is_dir() or source.stat().st_mode & 0o077:
        raise ValueError('Source must be a real server directory')
    path = source / 'cybos.conf'
    if path.is_symlink() or not path.is_file() or path.stat().st_mode & 0o077 or path.stat().st_size > 65536:
        raise ValueError('Invalid source configuration')
    text = path.read_text()
    # WireGuard permits repeated [Peer] sections; parse each separately and
    # accept only the intentionally small configuration generated by our helper.
    blocks = text.split('[Peer]')
    interface = configparser.ConfigParser(interpolation=None, strict=True)
    try:
        interface.read_string(blocks[0])
        if interface.sections() != ['Interface']:
            raise ValueError('Invalid interface section')
        values = dict(interface['Interface'])
        if set(values) != {'privatekey', 'address', 'listenport'} or values['address'] != '10.77.0.1/24':
            raise ValueError('Unsupported server configuration')
        private = public_key(values['privatekey'])
        port = values['listenport']
        if port != endpoint.rpartition(':')[2]:
            raise ValueError('Endpoint port must match the existing server ListenPort')
        keys, addresses = set(), set()
        for block in blocks[1:]:
            peer = configparser.ConfigParser(interpolation=None, strict=True)
            peer.read_string('[Peer]' + block)
            if peer.sections() != ['Peer']:
                raise ValueError('Unsupported peer sections')
            fields = dict(peer['Peer'])
            if set(fields) != {'publickey', 'allowedips'}:
                raise ValueError('Unsupported peer settings')
            key, ip = validate(endpoint, fields['allowedips'], fields['publickey'])
            if key in keys or ip in addresses:
                raise ValueError('Source contains duplicate peer keys or addresses')
            keys.add(key)
            addresses.add(ip)
    except (configparser.Error, KeyError):
        raise ValueError('Malformed server configuration') from None
    if device_key in keys or address in addresses:
        raise ValueError('Device key or tunnel address is already enrolled')
    server_key = public_key(wg_run(tool, ['pubkey'], private + '\n'))
    if device_key == server_key or server_key in keys:
        raise ValueError('Server and device keys must differ')
    invitation = {'version': 1, 'endpoint': endpoint, 'server_key': server_key,
                  'address': address, 'network': '10.77.0.0/24'}
    config = text.rstrip() + f'\n\n[Peer]\nPublicKey = {device_key}\nAllowedIPs = {address}\n'
    output.mkdir(mode=0o700)
    write_new(output / 'cybos.conf', config)
    write_new(output / 'device-invitation.json', json.dumps(invitation, indent=2) + '\n')
    print('Prepared an additional peer. Original files and live tunnel are unchanged.')
    print('Public server key:', server_key)
    return invitation


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--server-dir', required=True)
    parser.add_argument('--output-dir', required=True)
    parser.add_argument('--endpoint', required=True)
    parser.add_argument('--device-public-key', required=True)
    parser.add_argument('--device-address', required=True)
    parser.add_argument('--wg', default='wg')
    args = parser.parse_args()
    try:
        enroll(args.server_dir, args.output_dir, args.endpoint, args.device_address, args.device_public_key, args.wg)
    except (ValueError, RuntimeError, OSError) as error:
        parser.exit(1, str(error) + '\n')


if __name__ == '__main__':
    main()
